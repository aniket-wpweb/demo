export async function getStaticProps(context) {
  const revalidateInterval = Number(process.env.REVALIDATE_INTERVAL);
  const {
    data: eCommerceWebsitePackagesData,
    loading,
    networkStatus,
  } = await client.query({
    query: eCommerceWebsitePackagesQuery,
  });

  const { data: footerData } = await client.query({
    query: FooterQuery,
  });

  const { data: testimaonialDetails } = await client.query({
    query: TestimonialQuery,
  });

  return {
    props: {
      eCommerceWebsitePackagesData: eCommerceWebsitePackagesData,
      footerData: footerData,
      testimaonialDetails: testimaonialDetails,
    },
    revalidate: revalidateInterval,
  };
}
